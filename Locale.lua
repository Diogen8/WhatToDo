function ns.Lang()
	local s = WhatToDoDB and WhatToDoDB.settings
	return (s and s.lang == "en") and "en" or "uk"
end

function ns.T(text)
	if text == nil then return nil end
	if ns.Lang() == "en" then return EN[text] or text end
	return text
end
