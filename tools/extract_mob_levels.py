"""Extracts NPC levels for MobLevels.lua from QuestieDB's baked TOC store (QuestieDB_Forever.toc).
Usage: python tools/extract_mob_levels.py <path to QuestieDB_Forever.toc> MobLevels.lua
Needs: pip install cbor2. Each "## X-Npc-<id>-S" line is base64 CBOR (a map or an array of fields):
field 4 = minLevel, 5 = maxLevel, 13 = friendlyToFaction ("AH" = friendly to both, skipped)."""
import base64, re, sys, cbor2, collections
TOC = sys.argv[1]
lines = open(TOC, encoding='utf-8', errors='replace').read().splitlines()
pat = re.compile(r'^## X-Npc-(\d+)-S(?:-(\d+))?: (.*)$')
parts = collections.defaultdict(dict)
heads = {}
for l in lines:
    m = pat.match(l)
    if not m: continue
    nid, part, val = int(m.group(1)), m.group(2), m.group(3)
    if part is None:
        heads[nid] = val
    else:
        parts[nid][int(part)] = val
stats = collections.Counter(); out = {}
for nid, v in heads.items():
    cm = re.match(r'^~(\d+)~$', v)
    if cm:
        n = int(cm.group(1)); v = ''.join(parts[nid].get(i, '') for i in range(1, n + 1)); stats['chunked'] += 1
    try:
        d = cbor2.loads(base64.b64decode(v))
    except Exception as e:
        stats['bad'] += 1; continue
    if isinstance(d, list): d = {i + 1: v for i, v in enumerate(d)}
    lo, hi, friendly = d.get(4), d.get(5), d.get(13)
    if isinstance(friendly, bytes): friendly = friendly.decode('utf-8', 'replace')
    if not isinstance(lo, int) or lo <= 0: stats['nolevel'] += 1; continue
    if not isinstance(hi, int) or hi < lo: hi = lo
    if friendly == 'AH': stats['friendly'] += 1; continue
    out[nid] = (min(lo, 99), min(hi, 99))  # scripted placeholders like 9999 clamp to 99 (= skull)
print(len(heads), 'npcs;', len(out), 'kept;', dict(stats), file=sys.stderr)
ids = sorted(out)
print(min(ids), max(ids), max(h for _, h in out.values()), file=sys.stderr)
for nid in [2926, 3125, 7809, 4467, 2655]:
    print(nid, out.get(nid), file=sys.stderr)
# Lua data file: one string "id,lo,hi;" parsed lazily on first use (smaller and faster to load than a table literal)
body = ';'.join(f'{i},{out[i][0]},{out[i][1]}' if out[i][0] != out[i][1] else f'{i},{out[i][0]}' for i in ids)
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by tools/extract_mob_levels.py. NPC levels for WoW Forever, taken from the QuestieDB\n')
    f.write('-- (Questie project) database: hostile or neutral NPCs only, "npcID,minLevel[,maxLevel]" separated by ";".\n')
    f.write('-- Do not edit by hand; re-run the tool when the game data changes.\n')
    f.write('local _, ns = ...\n')
    f.write('ns.MOB_LEVEL_DATA = "' + body + '"\n')
print(len(body), 'bytes', file=sys.stderr)
